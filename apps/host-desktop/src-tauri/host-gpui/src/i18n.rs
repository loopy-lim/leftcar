//! GPUI 호스트 UI 문안 표(계획 T-3). packages/ui-tokens/src/i18n.ts의
//! `host`·`common`·`km`·`viewer.advancedSettingsToggle` 키와 같은 문장을
//! Rust 표로 옮겨 담는다(lib 크레이트는 TS 패키지를 못 읽는다). 인코더
//! 진단 문장은 [`crate::state::encoder_diagnostics`]의 표를 그대로 쓰고,
