/// 화면 공유 세션의 전송 경로 라벨(SessionCard.sessionTransportLabel).
pub fn transport_label(media_transport: Option<&str>, language: HostLanguage) -> &'static str {
    let (usb, wifi, unknown) = match language {
        HostLanguage::Ko => ("USB 케이블", "Wi-Fi 무선", "확인 중"),
        HostLanguage::En => ("USB Cable", "Wi-Fi Wireless", "Checking"),
    };
    match media_transport {
        Some("usb") => usb,
        Some("udp") => wifi,
        Some(_) | None => unknown,
    }
}

/// 대시보드 헤더의 "연결 창 열기" 버튼 문안(T-4). 트레이 메뉴의 페어링
/// 라벨([`tray_menu_labels`])과 같은 문장을 재사용해 새 문구를 만들지
/// 않는다.
pub fn open_pairing_window_label(language: HostLanguage) -> &'static str {
    tray_menu_labels(language).1
}

