type DeepStringRecord<T> = {
  readonly [K in keyof T]: T[K] extends string ? string : DeepStringRecord<T[K]>;
};

export type TranslationSchema = DeepStringRecord<typeof translations.ko>;

export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    return key in params ? String(params[key]) : `{${key}}`;
  });
}

export function getTranslation(lang: SupportedLanguage): TranslationSchema {
  return translations[lang] ?? translations.ko;
}

